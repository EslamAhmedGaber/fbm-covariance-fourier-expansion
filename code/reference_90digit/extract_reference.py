"""Extract the 90-digit reference values used by study B2 from results/scaled_projection_257.json.

Writes results/reference_highprecision_D257.json (residual energies e_D(f)^2 and norms only).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(os.path.dirname(os.path.dirname(HERE)), 'results')
SOURCE = ("Residual energies e_D(f)^2 and norms computed by the authors' arbitrary-precision implementation "
          "(mpmath, 90 significant digits, nested Cholesky factorization of the raw Gram matrix) of the same "
          "projection; stored here as reference data. Setup times are those of that implementation. "
          "Generated by code/reference_90digit/run_scaled_projection.py and extracted by extract_reference.py.")


def main():
    src = json.load(open(os.path.join(RES, 'scaled_projection_257.json'), encoding='utf-8'))
    runs = []
    for r in src['runs']:
        runs.append({'H': r['H'], 'setup_seconds': r['setup_seconds'],
                     'inputs': [{'input': i['input'], 'reference_digits': i['reference_digits'],
                                 'rows': [{'D': w['D'], 'best_projection_error2': w['best_projection_error2'],
                                           'norm2': w['norm2']} for w in i['rows']]} for i in r['inputs']]})
    out = {'source': SOURCE, 'runs': runs}
    with open(os.path.join(RES, 'reference_highprecision_D257.json'), 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(out, fh, indent=1)
    print('wrote', sum(len(i['rows']) for r in runs for i in r['inputs']), 'reference rows')


if __name__ == '__main__':
    main()
